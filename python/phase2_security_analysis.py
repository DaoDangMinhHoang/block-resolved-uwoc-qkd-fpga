#!/usr/bin/env python3
"""
phase2_security_analysis.py (rev E)

WHAT IT COMPUTES

  V(G,T) = G * (1 - h2(T/G))            privacy entropy per attempt.
      The zero of this function is at e = 50%, not 11%. The 11% figure belongs
      to eq. (8), the Shor-Preskill RATE metric, which subtracts error
      correction. Do not conflate them.

  Delta_cg = sum_b p_b V(m_b) - V(sum_b p_b m_b)

      p_b is the number of PHYSICAL ATTEMPTS in bin b, and m_b = (C/N, E/N) is
      per attempt to match. Proposition 1's mixture weight is the round count;
      weighting by basis-matched trials instead folds basis-sampling noise into
      p_b for nothing.

  Gamma_0 = Hessian of V. In the reduced 2-D model it is rank one,
      Gamma = k v v^T with v = (-e0, 1), so the radial direction lies in its
      kernel. Pure multiplicative fading moves (G,T) along a ray and contributes
      exactly zero. Whatever defect is measured is generated by the background
      floor Y0 pushing deeply faded blocks off that ray. The Y0 = 0 control run
      is the experimental proof, and it must come out consistent with zero.

NEW IN REV E (2026-09-15)

  * phi(e) = 1 - h2(e) on [0, 1], unclipped (--clip-phi restores rev D). Then
        Delta_cg / G_bar = I(J; E | D)
    exactly: the plug-in mutual information between the bin label and the error
    bit of a sifted detection. Two consequences are used here:
      - the counting-noise null has the closed form (B-1)/(2 C ln 2) bits
        (Miller-Madow), a cross-check of the 600-replicate parametric null;
      - G = 2 C ln2 * I is the likelihood-ratio statistic of independence,
        chi2(B-1) under the radial null: per-group p-values and one global test
        over all Y0 = 0 groups (radial_null_gtest.csv).
  * --bin-scan: NESTED partitions 2, 4, ..., 128 plus every distinct h value,
    with block-bootstrap standard errors (bin_scan_nested.csv). Refinement can
    only raise the population defect along a nested chain; 4-6-8-12-16-24 is
    not nested.
  * --observable-label: blocks binned by the clicks of basis-MISMATCHED
    attempts. Bob announces them, and given the fading they are independent of
    the sifted error bits, so this label is available to the protocol and its
    defect is a lower bound on the latent-h defect (observable_label.csv).
  * equal-resolution model: ROM-exact population defect at the analysis bin
    count and at full resolution (rom_exact_model.py), added to
    security_summary.csv.
  * v6 captures with decoy intensities: the SIGNAL class is analysed here
    (total minus decoy minus vacuum). Key rates: decoy_security_analysis.py.

WHY BINS OF IRRADIANCE

  At 25 m a 65536-attempt block yields ~39 sifted detections, so the plug-in
  per-block estimator carries a bias of (B-1)/(2 C ln2) with B = number of
  blocks, i.e. ~2e-2 V, flat across L1-L5, while the true defect runs 1.3e-5
  to 3.5e-3. Aggregating counts inside irradiance bins divides that bias by the
  number of blocks per bin; the null removes the rest.

NOT RESOLVED IS NOT NEGATIVE

  Proposition 1 gives Delta_cg >= 0. A negative point estimate is estimator
  fluctuation, not physics. Levels whose bootstrap interval covers zero are
  reported as one-sided 95% upper limits, not as negative measurements.

USAGE

  python phase2_security_analysis.py --model-only --bins 8
  python phase2_security_analysis.py --csv nom_*.csv --y0-csv y0_*.csv --bins 8 \
      --bin-scan --observable-label
"""

