def _radial_null_global(summary):
    """One predeclared test for the radial-null prediction: the G statistics of
    all Y0 = 0 groups of one base configuration add up to chi2(sum dof)."""
    ctl = summary[summary["p_noise"] == 0]
    if ctl.empty:
        return
    rows = []
    for base, g in ctl.groupby(BASE_COLS, dropna=False):
        G, dof = float(g["G_stat"].sum()), int(g["G_dof"].sum())
        rows.append({**dict(zip(BASE_COLS, base)), "groups": len(g),
                     "levels": " ".join(g["label"]), "G_total": G, "dof": dof,
                     "p_global": float(chi2.sf(G, dof)),
                     "p_min_level": float(g["G_pvalue"].min()),
                     "p_min_bonferroni": min(1.0, float(g["G_pvalue"].min()) * len(g))})
    out = pd.DataFrame(rows)
    out.to_csv(OUT_DIR / "radial_null_gtest.csv", index=False)
    print("\nradial-null G-test over the Y0 = 0 groups:")
    print(out[["levels", "G_total", "dof", "p_global", "p_min_level",
               "p_min_bonferroni"]].to_string(index=False))


def _labels_for(values, q):
    if q == "all":
        return np.unique(values, return_inverse=True)[1].astype(np.int64)
    return pd.qcut(pd.Series(values), q=q, labels=False,
                   duplicates="drop").to_numpy().astype(np.int64)


def _scan_one(values, C, E, q, reps, rng):
    lab = _labels_for(values, q)
    nl = int(lab.max()) + 1
    I, Ct, nb, e0, eb = mutual_information(lab, C, E, nl)
    phi0 = 1.0 - float(h2(np.array([e0]))[0])
    mm = miller_madow_bits(nb, Ct)
    se = np.nan
    if reps:
        n = len(C)
        boot = []
        for _ in range(reps):
            idx = rng.integers(0, n, n)
            Ib, Cb, nbb, _, _ = mutual_information(lab[idx], C[idx], E[idx], nl)
            boot.append(Ib - miller_madow_bits(nbb, Cb))
        se = float(np.std(boot))
    G = 2.0 * Ct * LN2 * I
    return {"n_labels": nb, "excess_bits": I - mm, "se_bits": se,
            "excess_over_V": (I - mm) / phi0, "se_over_V": se / phi0,
            "MM_over_V": mm / phi0, "bins_e_gt_half": int(np.sum(eb > 0.5)),
            "G_pvalue": float(chi2.sf(G, nb - 1))}


