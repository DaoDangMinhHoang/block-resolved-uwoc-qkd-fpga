def _gllp_scan(summary, args):
    """Sweep intensity at ONE fixed operating point.

    The measured Q and e are calibrated back to nbar and e_pol, then Q(mu) and
    e(mu) are recomputed with the background Y0 HELD FIXED. Scaling Q linearly
    with mu while holding e constant would contradict the very mechanism this
    paper is about: as mu falls the signal falls but Y0 does not, so the QBER
    rises."""
    rows = []
    for base, sub in summary.groupby(BASE_COLS, dropna=False):
        for (turb, pn), g in sub.groupby(["turb", "p_noise"]):
            if pn == 0 or len(g) != 1:
                continue
            Q = float(g["Q_all_pool"].iloc[0])       # per emitted pulse
            q_sift = float(g["basis_sift_fraction"].iloc[0])
            e = float(g["QBER_pool"].iloc[0])          # sifted QBER
            m_meas = int(g["mu_level"].iloc[0])
            gain = 1 << int(g["mu_gain_log2"].iloc[0])
            y0 = pn / 2 ** 24
            mu_meas = MU_NOM * m_meas / 8.0 * gain
            if Q <= y0 or Q >= 1:
                continue
            nbar = -math.log((1.0 - Q) / (1.0 - y0))
            det = 1.0 - math.exp(-nbar)
            if det <= 0:
                continue
            e_pol = (e * Q - 0.5 * y0) / det
            for m in range(1, 16):
                mu = MU_NOM * m / 8.0
                nb = nbar * mu / mu_meas
                Qm = 1.0 - (1.0 - y0) * math.exp(-nb)
                Tm = e_pol * (1.0 - math.exp(-nb)) + 0.5 * y0
                em = Tm / Qm
                priv, rate, delta = gllp(Qm, em, mu, q_sift=q_sift)
                rows.append({"base": str(base), "turb": turb,
                             "p_noise": pn, "mu_level": m,
                             "mu": mu, "Q": Qm, "QBER": em,
                             "tagged_fraction": delta,
                             "V_GLLP_privacy": priv, "R_GLLP_secret": rate})
    if not rows:
        return
    gl = pd.DataFrame(rows)
    gl.to_csv(OUT_DIR / "gllp_intensity_scan.csv", index=False)
    print("\nGLLP intensity scan (tagged source, no decoy required) written to "
          "gllp_intensity_scan.csv")
    for (base, turb), one in gl.groupby(["base", "turb"]):
        _gllp_figure(one, turb, len(gl.groupby(["base", "turb"])))


