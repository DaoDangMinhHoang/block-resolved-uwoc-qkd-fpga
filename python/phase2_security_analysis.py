def h2(e):
    e = np.asarray(e, dtype=float)
    out = np.zeros_like(e)
    m = (e > 0.0) & (e < 1.0)
    x = e[m]
    out[m] = -(x * np.log2(x) + (1.0 - x) * np.log2(1.0 - x))
    return out


def phi(e):
    e = np.asarray(e, dtype=float)
    if CLIP_PHI:
        return np.maximum(0.0, 1.0 - h2(np.clip(e, 0.0, 0.5)))
    return 1.0 - h2(np.clip(e, 0.0, 1.0))


def V_priv(G, T):
    G = np.asarray(G, dtype=float)
    T = np.asarray(T, dtype=float)
    e = np.divide(T, G, out=np.zeros_like(T), where=G > 0)
    return G * phi(e)


def gamma_hessian(G0, T0):
    e0 = T0 / G0
    k = 1.0 / (math.log(2.0) * e0 * (1.0 - e0) * G0)
    return k * np.array([[e0 * e0, -e0], [-e0, 1.0]])


def exact_defect(G, T, w):
    w = np.asarray(w, dtype=float)
    w = w / w.sum()
    G0 = float(np.sum(w * G))
    T0 = float(np.sum(w * T))
    sep = float(np.sum(w * V_priv(G, T)))
    pooled = float(V_priv(np.array([G0]), np.array([T0]))[0])
    return sep - pooled, G0, T0, pooled


def bkm_defect(G, T, w):
    w = np.asarray(w, dtype=float)
    w = w / w.sum()
    G0 = float(np.sum(w * G))
    T0 = float(np.sum(w * T))
    Gam = gamma_hessian(G0, T0)
    d = np.column_stack([np.asarray(G) - G0, np.asarray(T) - T0])
    return 0.5 * float(np.sum(w * np.einsum("ni,ij,nj->n", d, Gam, d)))


def mutual_information(lab, C, E, nlab):
    """Plug-in I(J;E|D) in bits from per-block sifted clicks C and errors E.

    Returns (I, total clicks, occupied bins, pooled QBER, per-bin QBER)."""
    Cb = np.bincount(lab, weights=C, minlength=nlab)
    Eb = np.bincount(lab, weights=E, minlength=nlab)
    m = Cb > 0
    Cb, Eb = Cb[m], Eb[m]
    Ct = float(Cb.sum())
    e0 = float(Eb.sum() / Ct)
    eb = Eb / Cb
    I = float(h2(np.array([e0]))[0] - np.sum(Cb / Ct * h2(eb)))
    return I, Ct, int(m.sum()), e0, eb


def miller_madow_bits(n_bins, clicks):
    return (n_bins - 1) / (2.0 * clicks * LN2)


def gllp(Q, e, mu, f_ec=F_EC, q_sift=0.5):
    """Tagged-source GLLP, per EMITTED pulse.

    No decoy states required: the multiphoton probability of a Poissonian source
    is known a priori from mu, and every tagged detection is conceded to Eve.
    Decoy states improve the bound by estimating Y1 instead of assuming the
    worst; they are not a prerequisite for stating it.

    Q must be the TOTAL detection probability per emitted pulse,
    clicks_all / attempts. Passing the sifted gain instead overstates the tagged
    fraction Delta = p_multi/Q by the sifting factor, roughly 2x for unbiased
    BB84, which is enough to move the intensity optimum.

    q_sift is the basis-reconciliation factor, 1/2 for unbiased BB84. Both
    returned quantities are per emitted pulse. Only the second may be called a
    secure key rate; the first is a privacy contribution with no error-correction
    leakage subtracted."""
    p_multi = 1.0 - math.exp(-mu) * (1.0 + mu)
    if Q <= 0:
        return 0.0, 0.0, 1.0
    delta = min(p_multi / Q, 1.0)
    omega = 1.0 - delta
    if omega <= 0:
        return 0.0, 0.0, delta
    u = min(e / omega, 0.5)
    priv_raw = Q * omega * float(1.0 - h2(np.array([u]))[0])
    ec_raw = Q * f_ec * float(h2(np.array([e]))[0])
    return q_sift * priv_raw, q_sift * max(0.0, priv_raw - ec_raw), delta


