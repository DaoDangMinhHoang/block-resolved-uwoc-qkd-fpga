def load(paths, allow_invalid=False):
    frames = []
    for p in paths:
        d = pd.read_csv(p, low_memory=False)
        d["source"] = Path(p).name
        frames.append(d)
    df = pd.concat(frames, ignore_index=True)
    n0 = len(df)
    if not allow_invalid and "capture_valid" in df.columns:
        df = df[df["capture_valid"] == 1].copy()
    for col, default in (("decoy_enable", 0), ("mu_gain_log2", 0),
                         ("decoy_shift", 0), ("decoy_preset", 0), ("version", 5)):
        if col not in df.columns:
            df[col] = default
        df[col] = df[col].fillna(default).astype(int)
    # [rev E] with decoys on, the phase-2 functional is evaluated on the SIGNAL
    # class: total minus decoy minus vacuum.
    dec = df["decoy_enable"] == 1
    if dec.any():
        for name in CLASS_FIELDS:
            df.loc[dec, name] = (df.loc[dec, name] - df.loc[dec, "dec_" + name]
                                 - df.loc[dec, "vac_" + name])
    df["trials"] = df["trials_z"] + df["trials_x"]
    df["clicks"] = df["clicks_z"] + df["clicks_x"]
    df["errors"] = df["errors_z"] + df["errors_x"]
    df["mismatch_clicks"] = df["clicks_all"] - df["clicks"]
    df = df[(df["trials"] > 0) & (df["attempts"] > 0)].copy()
    df["h_q8"] = df["h_mean"] / 256.0
    print("loaded %d blocks from %d file(s), kept %d after gates"
          % (n0, len(paths), len(df)))
    if len(df) and (df["trials"] <= df["clicks"]).any():
        raise SystemExit("trials <= clicks in some blocks: evt_bmatch is not "
                         "valid on lost attempts. Fix PATCH item 3 and recapture.")
    return df


