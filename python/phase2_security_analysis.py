def _control_gt_figures(store, args):
    """Y0 = 0 and Y0 nominal on the SAME axes.

    This is the one picture that explains the whole result. With the background
    switched off the trajectory is a straight ray through the origin, because
    V is homogeneous of degree one and pure multiplicative fading only rescales
    (G,T); the defect is then exactly zero. Switching the background on bends
    the trajectory away from that ray, and the curvature is the defect."""
    keys = set((b, t) for (b, t, _p) in store)
    for base, turb in sorted(keys, key=lambda k: k[1]):
        nom_p = [p for (_b, _t, p) in store if _b == base and _t == turb and p != 0]
        nom = store.get((base, turb, nom_p[0])) if nom_p else None
        zer = store.get((base, turb, 0))
        if nom is None or zer is None:
            continue
        fig, ax = plt.subplots(figsize=(6.6, 4.8))
        for r, lbl, mk in ((zer, r"$Y_0 = 0$ control", "s--"),
                           (nom, r"$Y_0$ nominal", "o-")):
            b = r["binned"]
            ax.plot(b["G"], b["T"], mk, label=lbl)
        b = nom["binned"]
        gg = np.linspace(0, b["G"].max() * 1.05, 50)
        e0 = nom["stat"]["T0"] / nom["stat"]["G0"]
        ax.plot(gg, e0 * gg, "k:", lw=1, label=r"pooled ray $T = e_0 G$")
        ax.set_xlabel("detection gain G (per attempt)")
        ax.set_ylabel("error gain T (per attempt)")
        ax.set_title("Radial-null control, turbulence level %d" % turb)
        ax.legend()
        ax.grid(True, alpha=0.3)
        fig.tight_layout()
        fig.savefig(OUT_DIR / ("CONTROL_GT_turb%d.png" % turb), dpi=220)
        plt.close(fig)


