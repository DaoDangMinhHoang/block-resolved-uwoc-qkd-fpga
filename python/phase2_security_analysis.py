def assign_bins(df, n_bins):
    d = df.copy()
    try:
        d["h_bin"] = pd.qcut(d["h_q8"], q=n_bins, labels=False, duplicates="drop")
    except ValueError:
        d["h_bin"] = 0
    return d.dropna(subset=["h_bin"])


def aggregate(d):
    rows = []
    for bid, g in d.groupby("h_bin", observed=True):
        N = float(g["attempts"].sum())
        A = float(g["trials"].sum())
        C = float(g["clicks"].sum())
        E = float(g["errors"].sum())
        if N <= 0 or A <= 0:
            continue
        rows.append({"bin": int(bid),
                     "h": float(np.average(g["h_q8"], weights=g["attempts"])),
                     "N": N, "A": A, "C": C, "E": E,
                     "G": C / N, "T": E / N,        # per attempt
                     "G_tr": C / A, "T_tr": E / A,  # per trial, cross-check
                     "blocks": len(g)})
    return pd.DataFrame(rows).sort_values("h").reset_index(drop=True)


def stat_from_bins(b):
    # Per attempt throughout. A per-trial cross-check used to be reported here
    # but it was subtracted from the per-attempt null, which is a different
    # quantity; rather than carry two nulls the convention is simply fixed.
    w = b["N"].to_numpy()
    G = b["G"].to_numpy()
    T = b["T"].to_numpy()
    delta, G0, T0, V0 = exact_defect(G, T, w)
    return {"delta": delta, "bkm": bkm_defect(G, T, w),
            "G0": G0, "T0": T0, "V0": V0,
            "QBER": T0 / G0 if G0 > 0 else np.nan}


def parametric_null(assigned, reps, rng):
    """Redraw at the pooled operating point, keeping each block's attempt total
    and bin membership. Basis assignment is redrawn too, because with per-attempt
    moments the basis-matching fluctuation is part of the observed statistic."""
    N = assigned["attempts"].to_numpy(dtype=np.int64)
    bins = assigned["h_bin"].to_numpy()
    h = assigned["h_q8"].to_numpy()
    N_tot = int(N.sum())
    A_tot = int(assigned["trials"].sum())
    C_tot = int(assigned["clicks"].sum())
    E_tot = int(assigned["errors"].sum())
    if min(N_tot, A_tot, C_tot) <= 0:
        return np.array([]), np.array([])
    p_match = A_tot / N_tot
    g_trial = C_tot / A_tot
    e0 = E_tot / C_tot
    dl, bk = [], []
    for _ in range(reps):
        A = rng.binomial(N, p_match)
        C = rng.binomial(A, g_trial)
        E = rng.binomial(C, e0)
        b = aggregate(pd.DataFrame({"attempts": N, "trials": A, "clicks": C,
                                    "errors": E, "h_q8": h, "h_bin": bins}))
        if len(b) < 2:
            continue
        s = stat_from_bins(b)
        dl.append(s["delta"])
        bk.append(s["bkm"])
    return np.asarray(dl), np.asarray(bk)


def bootstrap(assigned, reps, rng):
    groups = [g for _, g in assigned.groupby("h_bin", observed=True)]
    dl, bk = [], []
    for _ in range(reps):
        parts = [g.iloc[rng.integers(0, len(g), len(g))] for g in groups]
        b = aggregate(pd.concat(parts, ignore_index=True))
        if len(b) < 2:
            continue
        s = stat_from_bins(b)
        dl.append(s["delta"])
        bk.append(s["bkm"])
    return np.asarray(dl), np.asarray(bk)


def analyse_group(group, n_bins, null_reps, boot_reps, rng):
    assigned = assign_bins(group, n_bins)
    binned = aggregate(assigned)
    if len(binned) < 2:
        return None
    stat = stat_from_bins(binned)
    dnull, bnull = parametric_null(assigned, null_reps, rng)
    dnm = float(np.mean(dnull)) if len(dnull) else np.nan
    bnm = float(np.mean(bnull)) if len(bnull) else np.nan
    bd, bb = bootstrap(assigned, boot_reps, rng) if boot_reps else \
        (np.array([]), np.array([]))
    if len(bd) and len(dnull):
        # Pair each bootstrap replicate with a random null replicate instead of
        # subtracting the null MEAN as if it were known exactly. At L1-L2 the
        # null is the same size as the signal, so its own sampling error is not
        # negligible.
        idx = rng.integers(0, len(dnull), size=len(bd))
        corr_d = bd - dnull[idx]
        d_lo, d_hi = np.percentile(corr_d, [2.5, 97.5])
        d_ul = max(0.0, float(np.percentile(corr_d, 95)))
        if len(bb) and len(bnull):
            jdx = rng.integers(0, len(bnull), size=len(bb))
            b_lo, b_hi = np.percentile(bb - bnull[jdx], [2.5, 97.5])
        else:
            b_lo = b_hi = np.nan
    else:
        d_lo = d_hi = d_ul = b_lo = b_hi = np.nan

    # [rev E] the same 8-bin table read as a contingency table
    lab = assigned["h_bin"].to_numpy().astype(np.int64)
    I, Ct, nb, e0, _ = mutual_information(
        lab, assigned["clicks"].to_numpy(float),
        assigned["errors"].to_numpy(float), int(lab.max()) + 1)
    G_stat = 2.0 * Ct * LN2 * I
    return {"binned": binned, "stat": stat,
            "delta_null": dnm, "bkm_null": bnm,
            "excess": stat["delta"] - dnm, "excess_bkm": stat["bkm"] - bnm,
            "d_lo": d_lo, "d_hi": d_hi, "d_ul95": d_ul,
            "b_lo": b_lo, "b_hi": b_hi,
            "n_blocks": len(group), "n_bins": len(binned),
            "mi_bits": I, "sift_clicks": Ct, "mm_bits": miller_madow_bits(nb, Ct),
            "G_stat": G_stat, "G_dof": nb - 1,
            "G_pvalue": float(chi2.sf(G_stat, nb - 1))}


