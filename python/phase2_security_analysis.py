def operating_point(distance_m, lam=450, y0=Y0_NOMINAL, mu=MU_NOM):
    s = SPECTRAL[lam]
    cw, bw = CW_532 * s, BW_532 * s
    geom = min(D_RX_M ** 2 /
               (math.pi * (distance_m * math.tan(THETA_DIV_RAD)) ** 2), 1.0)
    h_l = geom * math.exp(-F_ATT * cw * distance_m)
    return {"h_l": h_l, "nbar0": mu * h_l * ETA_DET,
            "e_pol": min(E0 + K_S * (1.0 - math.exp(-bw * distance_m)), 0.5),
            "y0": y0}


def moments_from_h(op, h):
    h = np.minimum(np.asarray(h, dtype=float), RTL_H_MAX)
    nbar = op["nbar0"] * h
    G = 1.0 - (1.0 - op["y0"]) * np.exp(-nbar)
    T = op["e_pol"] * (1.0 - np.exp(-nbar)) + 0.5 * op["y0"]
    return G, T


def sample_h(sigma2, size, rng):
    if sigma2 <= 0:
        return np.ones(size)
    if sigma2 < 1.0:
        v = math.log1p(sigma2)
        return np.exp(-0.5 * v + math.sqrt(v) * rng.standard_normal(size))
    k = brentq(lambda k: math.exp(gammaln(1 + 2 / k) - 2 * gammaln(1 + 1 / k))
               - 1.0 - sigma2, 0.05, 200.0)
    return math.exp(-gammaln(1 + 1 / k)) * rng.weibull(k, size)


