def _observable_label(df, args):
    """Latent fading word versus a protocol-observable label.

    The observable label is the number of clicks on basis-MISMATCHED attempts
    of the block. Bob announces every detection and both bases are public, so
    Alice and Bob both know it; it never touches the sifted error bits, and
    given the fading word it is independent of them. Binning by it is therefore
    a garbling of binning by h, and its defect can only be smaller."""
    rows = []
    gi = 0
    for key, group in df.groupby(GROUP_COLS, dropna=False, sort=True):
        if len(group) < 400 or int(key[GROUP_COLS.index("p_noise")]) == 0:
            continue
        kd = dict(zip(GROUP_COLS, key if isinstance(key, tuple) else (key,)))
        C = group["clicks"].to_numpy(float)
        E = group["errors"].to_numpy(float)
        for label_name, values in (("latent_h", group["h_mean"].to_numpy()),
                                   ("observable_mismatch_clicks",
                                    group["mismatch_clicks"].to_numpy())):
            for q in (2, 4, 8, 16):
                rng = np.random.default_rng(SEED + 5000 + gi)
                gi += 1
                r = _scan_one(values, C, E, q, args.scan_boot, rng)
                rows.append({**kd, "label": TURB_LABEL.get(int(kd["turb"])),
                             "block_label": label_name, "bins": q, **r})
    if not rows:
        return
    s = pd.DataFrame(rows)
    s.to_csv(OUT_DIR / "observable_label.csv", index=False)
    print("\nlatent vs observable block label (observable_label.csv):")
    with pd.option_context("display.width", 250):
        print(s.pivot_table(index=["label", "bins"], columns="block_label",
                            values="excess_over_V", aggfunc="first").to_string(
                                float_format=lambda v: "%.3e" % v))


