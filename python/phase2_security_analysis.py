def run_model(args):
    OUT_DIR.mkdir(exist_ok=True)
    rng = np.random.default_rng(SEED)
    op = operating_point(args.distance, 450)
    n_sift = (1 << 16) // 2
    print("clear ocean %.0f m, 450 nm: h_l=%.5f nbar=%.4e e_pol=%.4f"
          % (args.distance, op["h_l"], op["nbar0"], op["e_pol"]))
    print("NOTE: sigma^2 values are the Table I figures at the 20 m reference,\n"
          "      which is also what the BOARD draws from at 25 m: the range\n"
          "      offset round(log4(s2(d)/s2(20 m))) is 0 there. The continuous\n"
          "      model is ~1.5x larger at 25 m; that gap is RTL quantisation.\n")

    rows = []
    for lvl, s2 in SIGMA2_HO_20M.items():
        h = sample_h(s2, 400000, rng)
        G, T = moments_from_h(op, h)
        V0 = float(V_priv(np.array([G.mean()]), np.array([T.mean()]))[0])
        true = (float(V_priv(G, T).mean()) - V0) / V0

        op0 = operating_point(args.distance, 450, y0=0.0)
        Gz, Tz = moments_from_h(op0, h)
        V0z = float(V_priv(np.array([Gz.mean()]), np.array([Tz.mean()]))[0])
        null_true = (float(V_priv(Gz, Tz).mean()) - V0z) / V0z

        floor = 0.7213 / (n_sift * V0)
        need = (20.0 * floor * args.bins / true) if true > 0 else -1
        rows.append({"level": lvl, "sigma2_20m": s2, "true_over_V": true,
                     "y0zero_over_V": null_true,
                     "n_det_per_block": n_sift * float(G.mean()),
                     "plugin_floor_over_V": floor,
                     "binned_floor_at_2k": floor * args.bins / 2000.0,
                     "blocks_planning": int(np.ceil(need)) if need > 0 else -1})
    tab = pd.DataFrame(rows)
    tab.to_csv(OUT_DIR / "model_expectation.csv", index=False)
    print(tab.to_string(index=False))

    rom = rom_model.load_rom()
    rrows = []
    for turb in range(1, rom.ho.shape[0]):
        r = rom_model.point_defects(rom, turb=turb, bins=args.bins)
        rrows.append({"row": turb, "label": TURB_LABEL.get(turb), **r})
    rtab = pd.DataFrame(rrows)
    rtab.to_csv(OUT_DIR / "model_rom_exact.csv", index=False)
    print("\nROM-exact population model (25 m, 450 nm, mu_level 8, Y0 code 218):")
    print(rtab[["label", "sigma2_realized", "d_bins_over_V", "d_full_over_V",
                "bkm_ratio_bins", "d_bins_bits", "QBER"]].to_string(
                    index=False, float_format=lambda v: "%.4g" % v))

    total = int(tab["blocks_planning"].clip(lower=0).sum())
    print("\nPLANNING ONLY. The factor 20 in blocks_planning is an empirical "
          "calibration against Monte Carlo of this pipeline, not a derived "
          "sample-complexity bound. Do not put this table in the paper; if a "
          "sample-size statement is needed, quote the measured bootstrap power.")
    print("\ncampaign with %d bins: %s blocks = %.2fe9 attempts"
          % (args.bins, format(total, ","), total * 65536 / 1e9))
    print("\nY0=0 column must be exactly zero to machine precision: that is the "
          "radial-null property, and the FPGA control run must reproduce it.")


